-- 1. Create BINS table
create table if not exists public.bins (
  id text primary key,
  location text not null default 'Sector F-7/1, Islamabad',
  capacity numeric not null default 100,
  current_level numeric not null default 0,
  distance_cm numeric, -- Raw ultrasonic distance from HC-SR04 sensor to waste level in cm
  status text not null default 'Safe', -- 'Safe' (<30%), 'Moderate' (30%-80%), 'Critical' (>80%)
  temperature numeric default 26.5,
  humidity numeric default 48.0,
  gas_level numeric default 18.0, -- Relative Gas Level Index from MQ-135 sensor
  updated_at timestamptz not null default now(),
  constraint chk_bins_current_level check (current_level >= 0 and current_level <= 100),
  constraint chk_bins_status check (status in ('Safe', 'Moderate', 'Critical'))
);

-- 2. Create SENSOR_DATA table
create table if not exists public.sensor_data (
  id bigint generated by default as identity primary key,
  bin_id text not null references public.bins(id) on delete cascade,
  garbage_level numeric not null,
  distance_cm numeric, -- Raw ultrasonic distance measurement in cm
  temperature numeric,
  humidity numeric,
  gas_level numeric, -- Relative Gas Level Index from MQ-135 sensor
  timestamp timestamptz not null default now(),
  constraint chk_sensor_garbage_level check (garbage_level >= 0 and garbage_level <= 100)
);

-- 3. Create ALERTS table
create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  bin_id text not null references public.bins(id) on delete cascade,
  message text not null,
  created_at timestamptz not null default now(),
  is_resolved boolean not null default false
);

-- 4. Safe Idempotent Schema Migrations (Columns & Check Constraints)
alter table public.bins add column if not exists distance_cm numeric;
alter table public.bins add column if not exists lid_status text default 'CLOSED';
alter table public.sensor_data add column if not exists distance_cm numeric;
alter table public.sensor_data add column if not exists lid_status text default 'CLOSED';

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'chk_bins_current_level') then
    alter table public.bins add constraint chk_bins_current_level check (current_level >= 0 and current_level <= 100);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'chk_bins_status') then
    alter table public.bins add constraint chk_bins_status check (status in ('Safe', 'Moderate', 'Critical'));
  end if;

  if not exists (select 1 from pg_constraint where conname = 'chk_sensor_garbage_level') then
    alter table public.sensor_data add constraint chk_sensor_garbage_level check (garbage_level >= 0 and garbage_level <= 100);
  end if;
end $$;

-- 5. Create Indexes for Foreign Keys & Time-Series Query Performance
create index if not exists idx_sensor_data_bin_id on public.sensor_data(bin_id);
create index if not exists idx_sensor_data_timestamp on public.sensor_data(timestamp desc);
create index if not exists idx_alerts_bin_id on public.alerts(bin_id);
create index if not exists idx_alerts_created_at on public.alerts(created_at desc);

-- 6. Enable Row Level Security (RLS)
alter table public.bins enable row level security;
alter table public.sensor_data enable row level security;
alter table public.alerts enable row level security;

